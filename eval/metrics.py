"""Eval metrics: ablation configs, worst-case selection and RESULTS.md rendering."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ai_safety_framework.detectors.regex_detectors import KeywordInputDetector
from ai_safety_framework.guardrails.layer import GuardrailsLayer
from ai_safety_framework.schemas import OWASP_CATEGORIES, AttackResult, RedTeamReport

_SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3}

_OWASP_TITLES = {
    "LLM01_prompt_injection": "LLM01 Prompt Injection",
    "LLM02_insecure_output": "LLM02 Insecure Output",
    "LLM03_training_poison": "LLM03 Training Data Poisoning",
    "LLM04_model_dos": "LLM04 Model Denial of Service",
    "LLM05_supply_chain": "LLM05 Supply Chain",
    "LLM06_info_disclosure": "LLM06 Info Disclosure",
    "LLM07_insecure_plugin": "LLM07 Insecure Plugin Design",
    "LLM08_excessive_agency": "LLM08 Excessive Agency",
    "LLM09_overreliance": "LLM09 Overreliance",
    "LLM10_model_theft": "LLM10 Model Theft",
}


def ablation_layers() -> dict[str, GuardrailsLayer | None]:
    """Return the guardrail configurations compared in the ablation.

    ``none`` is the baseline (no guardrails); ``input_only`` and ``output_only``
    isolate each direction; ``full_regex`` is both. The ML layer is documented as
    pending (Hugging Face blocked in this environment).
    """
    return {
        "none": None,
        "input_only": GuardrailsLayer(
            input_detectors=[KeywordInputDetector()], mode="regex_input_only"
        ),
        "output_only": GuardrailsLayer(input_detectors=[], mode="regex_output_only"),
        "full_regex": GuardrailsLayer(input_detectors=[KeywordInputDetector()], mode="regex"),
    }


def pct(x: float) -> str:
    """Format a 0-1 fraction as a percentage string."""
    return f"{x * 100:.1f}%"


def worst_cases(baseline: RedTeamReport, limit: int = 10) -> list[AttackResult]:
    """Return the ``limit`` most severe successful attacks against the baseline."""
    successes = [r for r in baseline.results if r.success]
    return sorted(successes, key=lambda r: _SEVERITY_ORDER[r.severity])[:limit]


def render_results_md(scenarios: list[dict[str, Any]]) -> str:
    """Render eval/RESULTS.md from the list of saved scenario documents."""
    lines: list[str] = []
    lines.append("# Evaluation results\n")
    lines.append(
        "Generated by `python -m eval.run`. Every number here comes from a run saved "
        "under `eval/runs/*.json` in this repo. Runs against a system that had no LLM "
        "configured are labelled **deterministic fallback, no LLM** and do not represent "
        "the quality of the target under a real model. Cells that need a key read "
        "`pendiente (requiere ANTHROPIC_API_KEY)`.\n"
    )

    for sc in scenarios:
        base = RedTeamReport.model_validate(sc["baseline"])
        guard = RedTeamReport.model_validate(sc["guardrailed"])
        fp = sc["fp_report"]
        reduction = base.success_rate - guard.success_rate
        lines.append(f"## {sc['scenario']} — {sc['target_label']}\n")
        lines.append(f"_{sc['sut_note']}_\n")
        lines.append(
            f"- Attacks: {base.n_attacks} · Legit queries: {fp['n_queries']} · "
            f"Corpus: own (106) + external sample\n"
            f"- Baseline success: **{pct(base.success_rate)}** → "
            f"with guardrails: **{pct(guard.success_rate)}** "
            f"(reduction {pct(reduction)})\n"
            f"- Guardrail FP rate: **{pct(fp['fp_rate'])}** "
            f"(tricky {pct(fp['tricky_fp_rate'])}) · "
            f"mean guardrail latency {guard.guardrail_latency_ms_mean:.3f} ms\n"
            f"- LLM target run: {sc.get('llm_status', 'pendiente (requiere ANTHROPIC_API_KEY)')}\n"
        )
        lines.append("\n**Mandatory table — attack success by OWASP category**\n")
        lines.append(
            "| OWASP category | Attack success (baseline) | Attack success (guardrails) | FP rate |"
        )
        lines.append("|---|---|---|---|")
        for cat in OWASP_CATEGORIES:
            b = base.by_category.get(cat)
            g = guard.by_category.get(cat)
            b_txt = f"{pct(b.success_rate)} ({b.n_success}/{b.n_attacks})" if b else "n/a"
            g_txt = f"{pct(g.success_rate)} ({g.n_success}/{g.n_attacks})" if g else "n/a"
            lines.append(f"| {_OWASP_TITLES[cat]} | {b_txt} | {g_txt} | {pct(fp['fp_rate'])} |")
        lines.append(
            f"| **Overall** | **{pct(base.success_rate)}** | "
            f"**{pct(guard.success_rate)}** | **{pct(fp['fp_rate'])}** |"
        )
        lines.append("")

        if sc.get("ablation"):
            lines.append("**Ablation — guardrail configuration vs attack success**\n")
            lines.append("| Configuration | Attack success | Δ vs no guardrails |")
            lines.append("|---|---|---|")
            base_rate = sc["ablation"].get("none", base.success_rate)
            for name, rate in sc["ablation"].items():
                delta = rate - base_rate
                lines.append(f"| {name} | {pct(rate)} | {pct(delta)} |")
            lines.append("")

        worst = sc.get("worst_cases", [])
        if worst:
            lines.append("**Worst findings (top successful attacks by severity)**\n")
            lines.append("| Attack | Category | Severity | Technique |")
            lines.append("|---|---|---|---|")
            for w in worst:
                cat = w["category"].split("_")[0]
                lines.append(f"| {w['attack_id']} | {cat} | {w['severity']} | {w['technique']} |")
            lines.append("")

    lines.append("## Baselines and provenance\n")
    lines.append(
        "- **regex baseline** is the always-on guardrail (no model download).\n"
        "- **ML detectors** (DeBERTa prompt-injection, toxic-bert, Presidio) sit behind the "
        "same `Detector` protocol and are unit-tested with mocks; a real ablation against them "
        "is `pendiente` because Hugging Face is blocked in this environment.\n"
        "- **LLM-as-judge** compliance scoring and the **LLM red-teamer** are implemented and "
        "mocked in tests; real scores are `pendiente (requiere ANTHROPIC_API_KEY)`.\n"
    )
    return "\n".join(lines) + "\n"


def load_scenarios(runs_dir: Path) -> list[dict[str, Any]]:
    """Load every saved scenario JSON in ``runs_dir``, sorted by filename."""
    scenarios: list[dict[str, Any]] = []
    for path in sorted(runs_dir.glob("*.json")):
        scenarios.append(json.loads(path.read_text()))
    return scenarios
